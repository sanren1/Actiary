const val ALL_MUSCLE_MASK: Int = (1 shl 14) - 1

fun muscleMaskOf(vararg groups: MuscleGroup): Int {
    var mask = 0
    for (group in groups) {
        mask = mask or (1 shl group.bit)
    }
    return mask
}

fun musclesFromMask(mask: Int): Set<MuscleGroup> {
    if (mask == 0) return emptySet()
    val result = LinkedHashSet<MuscleGroup>()
    for (group in MuscleGroup.entries) {
        if ((mask and (1 shl group.bit)) != 0) {
            result += group
        }
    }
    return result
}

enum class MuscleActivation {
    NONE,
    SECONDARY,
    PRIMARY,
}

/**
 * Aggregates primary and secondary muscle masks across a day's strength items.
 * Primary activation overrides secondary activation for the same muscle; uninvolved muscles are omitted.
 */
fun computeDayMuscleHighlights(items: List<Pair<Int, Int>>): Map<MuscleGroup, MuscleActivation> {
    if (items.isEmpty()) return emptyMap()
    var primaryAll = 0
    var secondaryAll = 0
    for ((primaryMask, secondaryMask) in items) {
        primaryAll = primaryAll or primaryMask
        secondaryAll = secondaryAll or secondaryMask
    }
    val highlights = LinkedHashMap<MuscleGroup, MuscleActivation>()
    for (muscle in MuscleGroup.entries) {
        val bitMask = 1 shl muscle.bit
        when {
            (primaryAll and bitMask) != 0 -> highlights[muscle] = MuscleActivation.PRIMARY
            (secondaryAll and bitMask) != 0 -> highlights[muscle] = MuscleActivation.SECONDARY
        }
    }
    return highlights
}

/**
 * Recommends the next workout plan in a cyclic list after [lastUsedPlanId].
 * Returns the first plan when [lastUsedPlanId] is null or missing from [orderedPlanIds],
 * or null when [orderedPlanIds] is empty.
 */
fun recommendNextPlanId(orderedPlanIds: List<Long>, lastUsedPlanId: Long?): Long? {
    if (orderedPlanIds.isEmpty()) return null
    if (lastUsedPlanId == null) return orderedPlanIds.first()
    val lastIndex = orderedPlanIds.indexOf(lastUsedPlanId)
    if (lastIndex < 0) return orderedPlanIds.first()
    return orderedPlanIds[(lastIndex + 1) % orderedPlanIds.size]
}

private val MIN_WEIGHT_KG = 0.5.toBigDecimal()
private val MAX_WEIGHT_KG = 500.0.toBigDecimal()

fun parseWeightKg(raw: String): Float? {
    val trimmed = raw.trim()
    if (trimmed.isEmpty()) return null
    val decimal = trimmed.toBigDecimalOrNull() ?: return null
    if (decimal < MIN_WEIGHT_KG || decimal > MAX_WEIGHT_KG) return null
    val rounded = decimal.setScale(1, RoundingMode.HALF_UP)
    if (rounded < MIN_WEIGHT_KG || rounded > MAX_WEIGHT_KG) return null
    return rounded.toFloat()
}

fun formatWeightKg(kg: Float): String {
    val tenths = (kg * 10f).roundToInt()
    return if (tenths % 10 == 0) {
        (tenths / 10).toString()
    } else {
        String.format(Locale.US, "%.1f", tenths / 10.0)
    }
}

